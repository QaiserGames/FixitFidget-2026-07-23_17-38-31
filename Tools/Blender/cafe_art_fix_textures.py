def hexrgb(h):
    h = h.lstrip('#')
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def luminance(rgb):
    def lin(c):
        c = c / 255.0
        return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4
    r, g, b = (lin(c) for c in rgb)
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def contrast(a, b):
    la, lb = luminance(a), luminance(b)
    hi, lo = max(la, lb), min(la, lb)
    return (hi + 0.05) / (lo + 0.05)


def font(weight, px):
    path = os.path.join(BALOO, 'Baloo2-%s.ttf' % weight)
    if not os.path.exists(path):
        raise FileNotFoundError(path + ' (the game\'s own font; run this from the repository)')
    return ImageFont.truetype(path, px)


def out_path(folder, name):
    if folder:
        os.makedirs(folder, exist_ok=True)
        return os.path.join(folder, name)
    d = os.path.join(REPO, FOLDERS[name]) if IN_REPO else os.path.join(HERE, 'tex')
    os.makedirs(d, exist_ok=True)
    return os.path.join(d, name)


