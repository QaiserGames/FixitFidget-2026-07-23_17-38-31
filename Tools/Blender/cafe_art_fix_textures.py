def draw_screen(folder=None):
    """
    LI_Screen.png: the laptop's screen on (art audit a50: "a flat light-blue panel. It reads as a dead screen"; the fix: "a
    two-tone screen texture: a dark title bar over a page"). Drawn at the glass's own 3:2 (768 x 512) and stretched to
    1024 x 512: a charcoal title bar with the three window buttons and a pale title, a warm-white page with a light
    sidebar, a bold heading, ten lines of text as soft grey bars (no words: at the table's distance they would be noise),
    and a sage picture block. The top-left texel is the bar's charcoal (cafe_livedin sends the glass's edges there).
    """
    W, H = 768, 512
    bar, page, side, ink, soft, pic = (hexrgb(h) for h in ('#2A2E35', '#F3F1EA', '#E2DED3', '#3A3F47', '#B9B6AE', '#8FA58C'))
    im = Image.new('RGB', (W, H), page)
    d = ImageDraw.Draw(im)
    bh = 54                                               # the title bar: about a tenth of the height
    d.rectangle([0, 0, W, bh], fill=bar)
    for k, c in enumerate(('#D9705A', '#E0B04C', '#7FB069')):
        cx = 28 + k * 26
        d.ellipse([cx - 8, bh / 2 - 8, cx + 8, bh / 2 + 8], fill=hexrgb(c))
    d.rounded_rectangle([W / 2 - 120, bh / 2 - 7, W / 2 + 120, bh / 2 + 7], radius=7, fill=hexrgb('#9AA0A8'))
    d.rectangle([0, bh, 172, H], fill=side)                # the sidebar: five entries, the second picked
    for k in range(6):
        y = bh + 30 + k * 40
        if k == 1:
            d.rounded_rectangle([12, y - 12, 160, y + 14], radius=8, fill=hexrgb('#C9D4C6'))
        d.rounded_rectangle([26, y - 4, 26 + (110, 92, 120, 80, 104, 70)[k], y + 6], radius=5, fill=hexrgb('#8E8B84'))
    x0 = 204
    d.rounded_rectangle([x0, bh + 34, x0 + 330, bh + 58], radius=8, fill=ink)        # the heading
    d.rounded_rectangle([x0 + 360, bh + 30, W - 34, bh + 196], radius=10, fill=pic)   # a picture
    d.polygon([(x0 + 380, bh + 180), (x0 + 450, bh + 100), (x0 + 500, bh + 150), (x0 + 530, bh + 120), (W - 50, bh + 180)],
              fill=hexrgb('#6E8A6B'))
    d.ellipse([W - 92, bh + 50, W - 62, bh + 80], fill=hexrgb('#F2E2B0'))
    lines = (300, 330, 280, 320, 150, 0, 520, 500, 540, 380)
    for k, length in enumerate(lines):
        if length == 0:
            continue
        y = bh + 96 + k * 30 if k < 5 else bh + 240 + (k - 5) * 30
        d.rounded_rectangle([x0, y, x0 + length, y + 11], radius=5, fill=soft)
    im = im.resize((1024, 512), Image.LANCZOS)
    p = out_path(folder, 'LI_Screen.png')
    im.save(p)
    return p, {'bar vs page': round(contrast(bar, page), 2), 'text vs page': round(contrast(soft, page), 2)}


