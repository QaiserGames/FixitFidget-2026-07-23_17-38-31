def draw_photo(folder=None):
    """
    GH_Photo.png: Grace's snapshot (art audit a72: "Every photo is the same flat sepia colour, so every frame looks empty.
    Her story is a reunion, yet there are no faces on her walls"; the fix: "one small painted snapshot (a sky and two or
    three people)"). Painted flat, the way the house paints: a warm late-afternoon sky, a far blue shore, a sandy
    foreground, and three people standing close (the tallest in the middle with an arm across the others' shoulders),
    their faces turned to the camera: pale ovals with dark hair, no features (it is a small photo across a room).
    The old print's sepia stays in the warm border and the colours are a touch faded, as a 30-year-old print is.
    One picture serves every frame (GH_Photo is one material); a photo per frame can come later as 2D art.
    Drawn at 3:4 (384 x 512), the frames' own shape (grace_house: 0.10 x 0.14 to 0.42 x 0.56 of photo, 0.71 to 0.78
    across), and stretched to the 512 x 512 texture: grace_house maps it 0..1 over each photo, so it comes back to 3:4
    on the wall and the people keep their proportions.
    """
    W, N = 384, 512
    im = Image.new('RGB', (W, N), hexrgb('#E9DCC0'))
    d = ImageDraw.Draw(im)
    m = 18                                                 # the print's white border, yellowed
    sky_top, sky_bot = np.array(hexrgb('#9DB7C9'), float), np.array(hexrgb('#EAD3AE'), float)
    hz = int(N * 0.54)
    for y in range(m, hz):
        t = (y - m) / max(1, hz - m)
        d.line([(m, y), (W - m, y)], fill=tuple(int(c) for c in sky_top * (1 - t) + sky_bot * t))
    d.polygon([(m, hz), (m, hz - 26), (82, hz - 40), (142, hz - 22), (225, hz - 34), (300, hz - 18), (W - m, hz - 30), (W - m, hz)],
              fill=hexrgb('#6F8FA3'))                       # the far shore's hills
    d.rectangle([m, hz, W - m, int(N * 0.66)], fill=hexrgb('#5E86A0'))     # the water
    d.rectangle([m, int(N * 0.66), W - m, N - m], fill=hexrgb('#D9C29A'))  # the sand
    d.ellipse([276, 84, 316, 124], fill=hexrgb('#F6E7C2'))                 # the low sun

    def person(cx, foot, h, coat, hair, skin='#E7C3A1', trousers='#4F4A48'):
        # the heads a little large for the bodies (a sixth of the height, not a seventh), so they read as people from
        # across the room: the house's chunky, friendly proportions
        w = h * 0.30
        head = h * 0.16
        neck = foot - h * 0.80
        d.rounded_rectangle([cx - w * 0.36, foot - h * 0.45, cx + w * 0.36, foot], radius=int(w * 0.12), fill=hexrgb(trousers))
        d.rounded_rectangle([cx - w / 2, neck, cx + w / 2, foot - h * 0.38], radius=int(w * 0.25), fill=hexrgb(coat))
        d.ellipse([cx - head * 0.42, neck - head * 0.95, cx + head * 0.42, neck + head * 0.08], fill=hexrgb(skin))
        d.chord([cx - head * 0.46, neck - head * 1.02, cx + head * 0.46, neck - head * 0.20], 180, 360, fill=hexrgb(hair))
        return neck
    foot = N - m - 36
    c = W / 2
    person(c, foot, 286, '#D8C7A0', '#2C2420', skin='#D9B08C')     # the middle, tallest, in a cream coat, behind the others
    # the middle's arms go round the other two behind their necks (drawn before them), and only the hands show, one on
    # each far shoulder: an arm drawn over them hid the left one's face
    hands = []
    for (x0, x1, neck_at) in ((c - 20, c - 96, foot - 250 * 0.80), (c + 20, c + 96, foot - 236 * 0.80)):
        y1 = neck_at + 12
        d.line([(x0, foot - 286 * 0.80 + 10), (x1, y1)], fill=hexrgb('#D8C7A0'), width=14)
        hands.append((x1, y1))
    person(c - 68, foot, 250, '#B5533C', '#3B2A20')        # left: a rust coat, close against the middle
    person(c + 70, foot, 236, '#4E6E5D', '#6A4E36')        # right: a green jacket
    for x1, y1 in hands:
        d.ellipse([x1 - 9, y1 - 8, x1 + 9, y1 + 8], fill=hexrgb('#D9B08C'))                 # a hand on a shoulder
    im = im.filter(ImageFilter.GaussianBlur(0.8))
    arr = np.asarray(im).astype(float)                     # faded a little toward the print's warm paper
    arr = arr * 0.88 + np.array(hexrgb('#E9DCC0'), float) * 0.12
    im = Image.fromarray(np.clip(arr, 0, 255).astype(np.uint8))
    ImageDraw.Draw(im).rectangle([0, 0, W - 1, N - 1], outline=hexrgb('#E3D3B2'), width=m)
    im = im.resize((N, N), Image.LANCZOS)
    p = out_path(folder, 'GH_Photo.png')
    im.save(p)
    return p, {}


