def draw_till(folder=None):
    """
    CF_TillKeys.png and CF_TillScreen.png (art audit a34: "The keys are blank white and the screen is an empty green
    panel, on an otherwise good till"; the fix: "key labels and a price on the screen"). The keys: a 5 x 4 atlas
    (cafe_till.TILL_KEYS, the till's twenty caps as Ace sees them), a cell a key cap, cream (DC_Ceramic's #F2EFE8) with a
    soft shadow at its foot, the digits in Baloo 2 Bold, the words in SemiBold, dark warm ink; TOTAL in Ace's green. The
    screen: a backlit green display (DC_Note_Green's #B9DBA1 at its rim) at the panels' own shape (3.2 to 1) with a
    price, 4.50, in seven-segment digits drawn as polygons, and a small TOTAL tag.
    """
    W, H = TILL_ATLAS
    cream, ink, green = hexrgb('#F2EFE8'), hexrgb('#3A332C'), hexrgb('#24684B')    # TOTAL in Ace's green, a shade deeper to read
    im = Image.new('RGB', (W, H), cream)
    d = ImageDraw.Draw(im)
    cw, chh = W / len(TILL_KEYS[0]), H / len(TILL_KEYS)
    for r, row in enumerate(TILL_KEYS):
        for k, label in enumerate(row):
            x0, y0 = k * cw, r * chh
            d.rectangle([x0, y0 + chh - 10, x0 + cw, y0 + chh], fill=hexrgb('#DCD6CA'))   # the cap's lower lip, shaded
            words = not label.replace('.', '').isdigit() and label != '.'
            f = font('SemiBold', 26 if len(label) > 5 else 34 if len(label) > 3 else 40) if words else font('Bold', 76 if len(label) < 2 else 64)
            colour = green if label == 'TOTAL' else ink
            bb = d.textbbox((0, 0), label, font=f)
            tw, th = bb[2] - bb[0], bb[3] - bb[1]
            d.text((x0 + (cw - tw) / 2 - bb[0], y0 + (chh - 10 - th) / 2 - bb[1]), label, font=f, fill=colour)
    p1 = out_path(folder, 'CF_TillKeys.png')
    im.save(p1)

    sw, sh = 512, 160
    lcd, lit, off = hexrgb('#A9CF8E'), hexrgb('#1E3A24'), hexrgb('#9AC380')
    sc = Image.new('RGB', (sw, sh), lcd)
    ds = ImageDraw.Draw(sc)
    ds.rectangle([0, 0, sw - 1, sh - 1], outline=hexrgb('#B9DBA1'), width=6)

    SEG = {'0': 'abcdef', '1': 'bc', '2': 'abged', '3': 'abgcd', '4': 'fgbc', '5': 'afgcd', '6': 'afgedc', '7': 'abc',
           '8': 'abcdefg', '9': 'abcdfg'}

    def hseg(x0, x1, yc, t):                       # a horizontal segment: a long hexagon with pointed ends
        return [(x0, yc), (x0 + t / 2, yc - t / 2), (x1 - t / 2, yc - t / 2), (x1, yc), (x1 - t / 2, yc + t / 2), (x0 + t / 2, yc + t / 2)]

    def vseg(xc, y0, y1, t):                       # a vertical one
        return [(xc, y0), (xc + t / 2, y0 + t / 2), (xc + t / 2, y1 - t / 2), (xc, y1), (xc - t / 2, y1 - t / 2), (xc - t / 2, y0 + t / 2)]

    def digit(x, y, w, h, t, ch, colour):
        g = t * 0.35                               # the hairline gap between segments
        segs = {'a': hseg(x + g, x + w - g, y + t / 2, t), 'g': hseg(x + g, x + w - g, y + h / 2, t),
                'd': hseg(x + g, x + w - g, y + h - t / 2, t),
                'f': vseg(x + t / 2, y + t / 2 + g, y + h / 2 - g, t), 'b': vseg(x + w - t / 2, y + t / 2 + g, y + h / 2 - g, t),
                'e': vseg(x + t / 2, y + h / 2 + g, y + h - t / 2 - g, t), 'c': vseg(x + w - t / 2, y + h / 2 + g, y + h - t / 2 - g, t)}
        for name, poly in segs.items():
            ds.polygon([(px + (y + h - py) * 0.12, py) for px, py in poly], fill=colour if name in SEG[ch] else off)   # a slight slant
    x, top = 170, 28
    for c in '450':
        digit(x, top, 74, 104, 13, c, lit)
        x += 104
        if x == 274:                                   # the decimal point after the first digit
            ds.ellipse([x - 20, top + 104 - 15, x - 5, top + 104], fill=lit)
    ds.text((22, 36), 'TOTAL', font=font('Bold', 34), fill=lit)
    ds.text((26, 78), '$', font=font('Bold', 52), fill=lit)
    p2 = out_path(folder, 'CF_TillScreen.png')
    sc.save(p2)
    return (p1, p2), {'key print vs cap': round(contrast(ink, cream), 2), 'TOTAL vs cap': round(contrast(green, cream), 2),
                      'digits vs display': round(contrast(lit, lcd), 2)}


# ------------------------------------------------------------------------------------------------------------ a62 chalk

SLATE = '#2B2B28'
CHALK_NEW = '#E8E4DA'          # the audit's near-white
AMBER = '#E2A33E'              # the one accent line: the double rule under ACE'S CAFE


def chalk_up_aframe(src, folder=None):
    """
    CF_AFrame.png re-chalked (art audit a62: "The chalk is dim grey on charcoal (about 1.9 to 1), so the good words fade
    from across the street"; the fix: "Repaint the chalk near-white (#E8E4DA) with one amber or green line"). The board's
    lettering (League Gothic and Yellowtail, drawn by draw_cafe_textures.draw_aframe) is kept exactly: this reads its chalk
    back out of the picture (how far each pixel sits from the slate toward the old chalk), fills the gaps the chalk's
    tooth left inside each stroke, and lays it down again near-white and at full strength, so the words hold together from
    across the street; the double rule under ACE'S CAFE becomes the one amber line. The ghosts of last week's board stay
    as faint as they were. draw_aframe in draw_cafe_textures.py makes the same picture from the fonts (same colours,
    denser chalk), for a machine that has them.
    """
    im = np.asarray(Image.open(src).convert('RGB')).astype(np.float32)
    H, W = im.shape[:2]
    slate = np.array(hexrgb(SLATE), np.float32)
    lum = im @ np.array([0.2126, 0.7152, 0.0722], np.float32)
    board = np.median(lum)                                 # the slate as drawn (with its own soft noise)
    old_chalk = np.percentile(lum, 99.7)
    a = np.clip((lum - board - 6.0) / (old_chalk - board - 6.0), 0.0, 1.0)
    from scipy import ndimage
    solid = ndimage.grey_closing(a, size=(3, 3))           # the tooth's gaps inside a stroke closed
    solid = np.maximum(a, ndimage.gaussian_filter(solid, 0.6))
    strong = np.clip(solid * 1.35, 0.0, 1.0) ** 0.8         # full strength in the strokes, the soft dust kept soft
    strong = np.where(a < 0.06, a, strong)                 # the ghosts and the dust as they were
    chalk = np.array(hexrgb(CHALK_NEW), np.float32)
    out = im * (1.0 - strong[..., None]) + chalk * strong[..., None]
    # the amber line: the double rule under the name (draw_aframe: y 0.192 and 0.203 of 0.90, x 0.115..0.485 of 0.60)
    yy, xx = np.mgrid[0:H, 0:W]
    y0, y1 = int(H * 0.186 / 0.90), int(H * 0.209 / 0.90)
    x0, x1 = int(W * 0.10 / 0.60), int(W * 0.50 / 0.60)
    rule = (yy >= y0) & (yy <= y1) & (xx >= x0) & (xx <= x1) & (strong > 0.25)
    amber = np.array(hexrgb(AMBER), np.float32)
    out[rule] = im[rule] * (1.0 - strong[rule][..., None]) + amber * strong[rule][..., None]
    res = Image.fromarray(np.clip(out, 0, 255).astype(np.uint8))
    p = out_path(folder, 'CF_AFrame.png')
    res.save(p)
    stroke = strong > 0.85
    measured = tuple(int(c) for c in np.median(out[stroke & ~rule], axis=0)) if stroke.any() else hexrgb(CHALK_NEW)
    return p, {'chalk vs slate': round(contrast(hexrgb(CHALK_NEW), hexrgb(SLATE)), 2),
               'amber vs slate': round(contrast(hexrgb(AMBER), hexrgb(SLATE)), 2),
               'chalk as drawn (median of the strokes)': '#%02X%02X%02X' % measured,
               'its contrast to the board': round(contrast(measured, tuple(int(c) for c in np.median(im[a < 0.02], axis=0))), 2)}


DRAWERS = {'screen': draw_screen, 'photo': draw_photo, 'till': draw_till}


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument('--only', default='')
    ap.add_argument('--out', default='')
    ap.add_argument('--aframe-from', default='', help='the CF_AFrame.png to re-chalk (default: the project\'s own)')
    a = ap.parse_args(argv)
    only = [k for k in a.only.split(',') if k] or list(DRAWERS) + ['chalk']
    for key in only:
        if key == 'chalk':
            src = a.aframe_from or os.path.join(REPO, FOLDERS['CF_AFrame.png'], 'CF_AFrame.png')
            p, info = chalk_up_aframe(src, a.out or None)
        else:
            p, info = DRAWERS[key](a.out or None)
        print(key, p, info)


if __name__ == '__main__':
    main()
