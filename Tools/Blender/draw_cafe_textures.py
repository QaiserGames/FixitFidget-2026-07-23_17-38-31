def draw_drawer_labels(out_dir):
    """CF_DrawerLabels: 18 x 4 cells, row 0 = the top, col 0 = the leftmost as the room sees it; black caps on cream."""
    AW, AH = 4096, 512
    atlas = Image.new('RGB', (AW, AH))
    r = rng_for(831)
    caps = []
    for col in range(18):
        for row in range(4):
            word = DRAWERS[col][row]
            W, H = LABEL_CARD
            sh = Sheet(W, H, (256, 112), ss=3.0)
            tone = r.uniform(-0.035, 0.015)                                    # some cards older than others
            img = rgb('#EEE6D2')[None, None, :] * (1.0 + tone + 0.012 * smooth_noise((sh.H, sh.W), int(sh.p(0.004)), 832 + col * 4 + row))[..., None]
            img[..., 2] *= (1.0 + tone * 0.6)                                   # and the older ones yellower
            m = sh.mask()
            cap = 0.0150
            wd = fit_wdth(sh, word, cap, 0.07, W - 0.010)
            while line_width(sh, word, 'lg', cap, 0.07, wd) > W - 0.010 and cap > 0.0120:
                cap -= 0.0005
            caps.append(cap)
            dx, dy = r.uniform(-0.0008, 0.0008), r.uniform(-0.0004, 0.0004)     # typed and slid in by hand
            set_line(m, sh, word, 'lg', cap, W / 2 + dx, H / 2 + cap / 2 + dy, 'center', track=0.07, wdth=wd)
            img = paint_on(img, arr(m), INK, sh, 833, var=0.04)
            card = to_img(img).resize((sh.out[0], sh.out[1]), Image.LANCZOS)
            x0, x1 = int(round(col * AW / 18)), int(round((col + 1) * AW / 18))
            y0, y1 = int(round(row * AH / 4)), int(round((row + 1) * AH / 4))
            atlas.paste(card.resize((x1 - x0, y1 - y0), Image.LANCZOS), (x0, y0))
    atlas.save(os.path.join(out_dir, 'CF_DrawerLabels.png'), optimize=True)
    return min(caps), max(caps)


