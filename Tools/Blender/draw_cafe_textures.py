def gild(sheet, a, seed, outline_mm=7.0, shade_mm=(9.0, 9.0), bands=None):
    """
    Gold leaf on glass, seen from the street: burnished gold, lighter at the top of each letter and deeper at the foot
    (the gilder's shading), a fine bright edge, a dark outline and a dark shade set down and right. RGBA.
    bands: [(top_m, bottom_m)] of each line, for the shading.
    """
    H, W = a.shape
    inside = a > 0.5
    dist = ndimage.distance_transform_edt(~inside)
    r = sheet.p(outline_mm / 1000)
    outline = np.clip(r + 0.5 - dist, 0, 1)
    shade = np.clip(shift(outline, sheet.p(shade_mm[0] / 1000), sheet.p(shade_mm[1] / 1000)) - outline, 0, 1)
    yy = np.mgrid[0:H, 0:W][0].astype(np.float32)
    t = np.full((H, W), 0.5, np.float32)
    for (top, bot) in (bands or []):
        y0, y1 = sheet.p(top), sheet.p(bot)
        band = (yy >= y0 - sheet.p(0.10)) & (yy <= y1 + sheet.p(0.10))
        t[band] = np.clip((yy[band] - y0) / max(1.0, y1 - y0), 0, 1)
    light, mid, deep = rgb('#E9CF8E'), rgb(GOLD), rgb('#8C6A2F')
    col = np.where(t[..., None] < 0.5, mix(light, mid, (t / 0.5)[..., None]), mix(mid, deep, ((t - 0.5) / 0.5)[..., None]))
    burnish = smooth_noise((H, W), (max(3, int(sheet.p(0.004))), max(6, int(sheet.p(0.05)))), seed)
    burnish = ndimage.rotate(burnish, 35, reshape=False, order=1, mode='reflect')
    col = col * (1.0 + 0.07 * burnish)[..., None]
    edge = np.clip(a - shift(a, sheet.p(0.0018), sheet.p(0.0018)), 0, 1)       # the bright lip where leaf meets glass
    col = mix(col, rgb('#F6E7BC'), edge * 0.65)
    rgba = np.zeros((H, W, 4), np.float32)
    ink = rgb(INK)
    rgba[..., :3] = ink[None, None, :]
    rgba[..., 3] = np.maximum(shade * 0.82, outline) * 255
    rgba[..., :3] = mix(rgba[..., :3], col, a)
    return rgba


