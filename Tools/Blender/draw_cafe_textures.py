def rng_for(seed):
    return np.random.default_rng(seed)


def fft_noise(n, beta, seed, aniso=(1.0, 1.0), lowcut=1.0):
    """Seamless (periodic) noise on an n x n tile with a 1/f^beta spectrum; aniso stretches it (y, x). Range ~[-1, 1]."""
    r = rng_for(seed)
    white = r.standard_normal((n, n)).astype(np.float32)
    fy = np.fft.fftfreq(n)[:, None] * n / aniso[0]
    fx = np.fft.fftfreq(n)[None, :] * n / aniso[1]
    f = np.sqrt(fx * fx + fy * fy)
    f[0, 0] = 1.0
    amp = 1.0 / np.power(np.maximum(f, lowcut), beta)
    amp[0, 0] = 0.0
    out = np.real(np.fft.ifft2(np.fft.fft2(white) * amp)).astype(np.float32)
    out /= (np.abs(out).max() + 1e-9)
    return out


def band_noise(n, f0, f1, seed, aniso=(1.0, 1.0)):
    """Seamless noise with only the frequencies f0..f1 (cycles per tile), normalised to [-1, 1]."""
    r = rng_for(seed)
    white = r.standard_normal((n, n)).astype(np.float32)
    fy = np.fft.fftfreq(n)[:, None] * n / aniso[0]
    fx = np.fft.fftfreq(n)[None, :] * n / aniso[1]
    f = np.sqrt(fx * fx + fy * fy)
    amp = ((f >= f0) & (f <= f1)).astype(np.float32)
    out = np.real(np.fft.ifft2(np.fft.fft2(white) * amp)).astype(np.float32)
    out /= (np.abs(out).max() + 1e-9)
    return out


def smooth_noise(shape, cell, seed, order=3):
    """Non-tiling value noise for sign textures: random values every `cell` pixels (y, x), smoothly interpolated."""
    r = rng_for(seed)
    cy, cx = (cell, cell) if np.isscalar(cell) else cell
    gh, gw = int(shape[0] / cy) + 4, int(shape[1] / cx) + 4
    g = r.uniform(-1, 1, (gh, gw)).astype(np.float32)
    out = ndimage.zoom(g, (cy, cx), order=order)[:shape[0], :shape[1]]
    return out / (np.abs(out).max() + 1e-9)


def normal_map(height_m, tile_m, strength=1.0):
    """OpenGL tangent-space normals from a seamless height field in metres (rows go down the picture, +V goes up)."""
    n = height_m.shape[0]
    px = tile_m / n
    dhdu = (np.roll(height_m, -1, axis=1) - np.roll(height_m, 1, axis=1)) / (2 * px)
    dhdv = (np.roll(height_m, 1, axis=0) - np.roll(height_m, -1, axis=0)) / (2 * px)
    nx, ny, nz = -dhdu * strength, -dhdv * strength, np.ones_like(height_m)
    ln = np.sqrt(nx * nx + ny * ny + nz * nz)
    out = np.stack([nx / ln, ny / ln, nz / ln], axis=-1)
    return ((out * 0.5 + 0.5) * 255.0 + 0.5).clip(0, 255).astype(np.uint8)


def to_img(arr):
    return Image.fromarray(np.clip(arr + 0.5, 0, 255).astype(np.uint8))


def down2(arr):
    """Box-filter a (2n, 2n, ...) array to (n, n, ...): the supersampled tiles stay seamless."""
    return 0.25 * (arr[0::2, 0::2] + arr[1::2, 0::2] + arr[0::2, 1::2] + arr[1::2, 1::2])


def mix(a, b, t):
    """a to b by t; a t with one dimension fewer than the colours gets a channel axis."""
    t = np.asarray(t, np.float32)
    if t.ndim >= 1 and t.ndim == np.ndim(a) - 1:
        t = t[..., None]
    return a * (1 - t) + b * t


def smoothstep(e0, e1, x):
    t = np.clip((x - e0) / (e1 - e0), 0, 1)
    return t * t * (3 - 2 * t)


