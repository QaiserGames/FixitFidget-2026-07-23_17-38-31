def paper(sheet, hexcol, seed, fibre=0.012):
    return rgb(hexcol)[None, None, :] * (1.0 + fibre * smooth_noise((sheet.H, sheet.W), max(2, int(sheet.p(0.0025))), seed)
                                         + 0.01 * smooth_noise((sheet.H, sheet.W), max(4, int(sheet.p(0.04))), seed + 1))[..., None]


def body(img_mask, sh, lines, x, y0, cap, pitch, align='left', track=0.02, kind='lg', jitter=None):
    for i, t in enumerate(lines):
        set_line(img_mask, sh, t, kind, cap, x, y0 + i * pitch, align, track=track,
                 jitter=(jitter[0] + i, jitter[1]) if jitter else None)


