def chalk(a, sheet, seed, coverage=0.86):
    """Chalk on a board: the stroke only where the chalk caught the board's tooth, its edge rough."""
    H, W = a.shape
    r = rng_for(seed)
    fine = ndimage.gaussian_filter(r.uniform(0, 1, (H, W)).astype(np.float32), 0.7)
    fine = (fine - fine.min()) / (fine.max() - fine.min() + 1e-9)
    mid = smooth_noise((H, W), max(3, int(sheet.p(0.004))), seed + 1) * 0.5 + 0.5
    tooth = 0.65 * fine + 0.35 * mid
    t = np.quantile(tooth, 1.0 - coverage)
    keep = smoothstep(t - 0.04, t + 0.04, tooth)
    edge = wobble(a, sheet, 0.6, 6, seed + 2)
    return np.clip(edge * keep, 0, 1)


