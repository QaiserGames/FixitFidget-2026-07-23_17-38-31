def draw_mosaic(out_dir):
    """
    CF_Mosaic: ACE'S let into the floor inside the door, 2.40 x 1.20 m: cream tesserae on green, a black border.
    Tesserae 2 cm (halved to 1 cm where they meet a letter's edge, as a mosaicist cuts them), each a little out of
    square, its own shade, grout between. Upright in the picture; the mesh's UVs make it read from the door.
    """
    W, H, T = 2.40, 1.20, 0.020
    # the design at 2 mm a pixel: 0 green, 1 cream, 2 black
    dsh = Sheet(W, H, (1200, 600), ss=1.0)
    m = dsh.mask()
    set_line(m, dsh, 'ACE’S', 'lg', 0.62, W / 2, H / 2 + 0.31, 'center', track=0.16)
    design = np.zeros((dsh.H, dsh.W), np.uint8)
    design[np.asarray(m) > 127] = 1
    yy, xx = np.mgrid[0:dsh.H, 0:dsh.W]
    edge = np.minimum(np.minimum(xx, dsh.W - 1 - xx), np.minimum(yy, dsh.H - 1 - yy)) / dsh.ppm
    design[edge < 0.040] = 2                      # two rows of black
    design[(edge >= 0.040) & (edge < 0.060)] = 1  # one row of cream inside it (the threshold's line)
    sh = Sheet(W, H, (2048, 1024), ss=2.0)
    img = np.zeros((sh.H, sh.W, 3), np.float32)
    img[:] = rgb('#8F877B')                       # grout, a warm grey
    shade = np.zeros((sh.H, sh.W), np.float32)
    r = rng_for(801)
    cols = {0: (rgb('#2E7D5B'), rgb('#26704F'), rgb('#358865')), 1: (rgb('#EDE6D6'), rgb('#E4DBC8'), rgb('#F3EEE2')),
            2: (rgb('#25221F'), rgb('#1C1A18'), rgb('#302C28'))}
    canvas = Image.new('RGB', (sh.W, sh.H))
    cd = ImageDraw.Draw(canvas)
    canvas.paste((143, 135, 123), (0, 0, sh.W, sh.H))
    def cell_value(x0, y0, x1, y1):
        a = design[int(y0 * dsh.ppm):max(int(y0 * dsh.ppm) + 1, int(y1 * dsh.ppm)), int(x0 * dsh.ppm):max(int(x0 * dsh.ppm) + 1, int(x1 * dsh.ppm))]
        vals, counts = np.unique(a, return_counts=True)
        return vals[np.argmax(counts)], len(vals) > 1
    def tessera(x0, y0, s, v):
        g = 0.0022 + r.uniform(0, 0.0012)              # the joint
        pts = []
        for (cx, cy) in ((x0 + g / 2, y0 + g / 2), (x0 + s - g / 2, y0 + g / 2), (x0 + s - g / 2, y0 + s - g / 2), (x0 + g / 2, y0 + s - g / 2)):
            pts.append((sh.p(cx + r.uniform(-0.0012, 0.0012)), sh.p(cy + r.uniform(-0.0012, 0.0012))))
        a, b, c = cols[int(v)]
        t = r.uniform(0, 1)
        col = a * (1 - t) + (b if t < 0.5 else c) * t
        col = col * (1 + r.uniform(-0.035, 0.035))
        cd.polygon(pts, fill=tuple(int(max(0, min(255, q))) for q in col))
    nx, ny = int(round(W / T)), int(round(H / T))
    for j in range(ny):
        for i in range(nx):
            x0, y0 = i * T, j * T
            v, mixed = cell_value(x0, y0, x0 + T, y0 + T)
            if not mixed:
                tessera(x0, y0, T, v)
            else:
                for (dx, dy) in ((0, 0), (T / 2, 0), (0, T / 2), (T / 2, T / 2)):
                    v2, _ = cell_value(x0 + dx, y0 + dy, x0 + dx + T / 2, y0 + dy + T / 2)
                    tessera(x0 + dx, y0 + dy, T / 2, v2)
    img = np.asarray(canvas, np.float32)
    # each tessera catches light on its upper-left edge and sinks a little at the joint
    lum = img.mean(axis=2)
    tile = (np.abs(lum - 135) > 6).astype(np.float32)
    rim = np.clip(tile - shift(tile, sh.p(0.0012), sh.p(0.0012)), 0, 1)
    img = img * (1.0 + 0.07 * rim)[..., None]
    img *= (1.0 + 0.02 * smooth_noise(lum.shape, int(sh.p(0.3)), 802))[..., None]
    sh.save(img, os.path.join(out_dir, 'CF_Mosaic.png'))


