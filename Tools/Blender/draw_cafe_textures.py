# ----------------------------------------------------------------------------------------------------------- B. words
#
# A face is drawn on square pixels at a real scale (Sheet: metres in, pixels out), supersampled, then resized to its
# power-of-two texture. Lettering: League Gothic (names, headings, labels) and Yellowtail (one accent line a sign).
# The hand-made part is the spacing and the paint, not distress: capitals letter-spaced as a sign painter spaces them
# (the font's kerning kept), lines on a true baseline, a painter's edge that wanders a fraction of a millimetre, paint
# a touch uneven, gold leaf burnished with a dark outline and a shade, chalk with the board's tooth in it.


class Sheet:
    """One lettered face: w_m x h_m metres, drawn at ss x the output's density on square pixels, saved at out (w, h)."""

    def __init__(self, w_m, h_m, out, ss=2.0):
        self.w_m, self.h_m, self.out = w_m, h_m, out
        self.ppm = max(out[0] * ss / w_m, out[1] * ss / h_m)
        self.W, self.H = int(round(w_m * self.ppm)), int(round(h_m * self.ppm))

    def p(self, m):
        return m * self.ppm

    def mask(self):
        return Image.new('L', (self.W, self.H), 0)

    def save(self, arr, path):
        im = to_img(arr) if isinstance(arr, np.ndarray) and arr.ndim == 3 and arr.shape[2] == 3 else arr
        if isinstance(arr, np.ndarray) and arr.ndim == 3 and arr.shape[2] == 4:
            im = Image.fromarray(np.clip(arr + 0.5, 0, 255).astype(np.uint8), 'RGBA')
        im = im.resize(self.out, Image.LANCZOS)
        im.save(path, optimize=True)
        return im


_FONTS = {}


def font(kind, cap_px, wdth=100):
    size = max(4, int(round(cap_px / (LG_CAP if kind == 'lg' else YT_CAP))))
    key = (kind, size, wdth)
    if key not in _FONTS:
        f = ImageFont.truetype(LG_PATH if kind == 'lg' else YT_PATH, size)
        if kind == 'lg' and wdth != 100:
            f.set_variation_by_axes([wdth])
        _FONTS[key] = f
    return _FONTS[key]


def line_width(sheet, text, kind, cap_m, track=0.0, wdth=100):
    f = font(kind, sheet.p(cap_m), wdth)
    dots = text.count('\u00b7') if kind == 'lg' else 0
    return (f.getlength(text) + track * sheet.p(cap_m) * (len(text) - 1) + 0.38 * sheet.p(cap_m) * dots) / sheet.ppm


def fit_wdth(sheet, text, cap_m, track, max_w, lo=75):
    """The widest League Gothic (100 down to lo) that keeps the line inside max_w metres."""
    for w in range(100, lo - 1, -5):
        if line_width(sheet, text, 'lg', cap_m, track, w) <= max_w:
            return w
    return lo


def set_line(img, sheet, text, kind, cap_m, x_m, base_m, align='left', track=0.0, wdth=100, fill=255, jitter=None):
    """
    One line on a true baseline. track: extra space between letters, as a fraction of the cap height (a sign
    painter's spacing; the font's kerning is kept). League Gothic's middle dot is raised to the capitals' middle.
    jitter (seed, amount): a hand-printed line, each letter a little turned, lifted and sized (marker notes).
    Returns the line's (x0, x1) in metres.
    """
    draw = ImageDraw.Draw(img)
    cap_px = sheet.p(cap_m)
    f = font(kind, cap_px, wdth)
    t_px = track * cap_px
    width = f.getlength(text) + t_px * (len(text) - 1)
    x = sheet.p(x_m) - (width / 2 if align == 'center' else width if align == 'right' else 0)
    y = sheet.p(base_m)
    if kind == 'yt' and not jitter:
        draw.text((x, y), text, font=f, fill=fill, anchor='ls')           # a script joins up: set it whole
        return x / sheet.ppm, (x + width) / sheet.ppm
    r = rng_for(jitter[0]) if jitter else None
    dots = text.count('\u00b7') if kind == 'lg' else 0
    extra = 0.38 * cap_px                                 # the air a painter leaves round a separator dot
    if dots and align != 'left':
        x -= (extra * dots) / (2 if align == 'center' else 1)
    seen = 0
    for i, ch in enumerate(text):
        xi = x + f.getlength(text[:i + 1]) - f.getlength(ch) + t_px * i + extra * seen
        dy = 0.0
        if ch == '\u00b7' and kind == 'lg':
            cx = xi + (f.getlength(ch) + extra) / 2
            rr = 0.085 * cap_px
            draw.ellipse([cx - rr, y - cap_px / 2 - rr, cx + rr, y - cap_px / 2 + rr], fill=fill)
            seen += 1
            continue
        if jitter and ch != ' ':
            amt = jitter[1]
            g = font(kind, cap_px * (1 + r.uniform(-0.06, 0.06) * amt), wdth)
            tile = Image.new('L', (int(cap_px * 2.2) + 8, int(cap_px * 2.2) + 8), 0)
            ImageDraw.Draw(tile).text((4, cap_px * 1.6), ch, font=g, fill=255, anchor='ls')
            tile = tile.rotate(r.uniform(-5, 5) * amt, resample=Image.BICUBIC, center=(4 + cap_px * 0.25, cap_px * 1.6 - cap_px * 0.5))
            ox, oy = int(xi - 4), int(y - cap_px * 1.6 + r.uniform(-0.05, 0.05) * cap_px * amt)
            region = img.crop((ox, oy, ox + tile.width, oy + tile.height))
            img.paste(Image.fromarray(np.maximum(np.asarray(region), np.asarray(tile) * (fill / 255.0)).astype(np.uint8)), (ox, oy))
            continue
        draw.text((xi, y + dy), ch, font=f, fill=fill, anchor='ls')
    return x / sheet.ppm, (x + width + extra * dots) / sheet.ppm


def arr(mask):
    return np.asarray(mask, np.float32) / 255.0


def wobble(a, sheet, amp_mm=0.35, wave_mm=14, seed=1):
    """A painter's edge: the outline wanders a fraction of a millimetre (amp_mm) over a few centimetres (wave_mm)."""
    if amp_mm <= 0:
        return a
    amp = sheet.p(amp_mm / 1000.0)
    cell = max(4, int(sheet.p(wave_mm / 1000.0)))
    dy = smooth_noise(a.shape, cell, seed) * amp
    dx = smooth_noise(a.shape, cell, seed + 1) * amp
    yy, xx = np.mgrid[0:a.shape[0], 0:a.shape[1]].astype(np.float32)
    return ndimage.map_coordinates(a, [yy + dy, xx + dx], order=1, mode='nearest')


def painted(sheet, hexcol, seed, mottle=0.014, streak=0.016, stroke='h'):
    """A brushed ground: a flat colour, faintly mottled, with the brush's direction in it."""
    H, W = sheet.H, sheet.W
    m = smooth_noise((H, W), max(8, int(sheet.p(0.18))), seed)
    if stroke == 'h':
        s = smooth_noise((H, W), (max(2, int(sheet.p(0.003))), max(8, int(sheet.p(0.20)))), seed + 1, order=1)
    else:
        s = smooth_noise((H, W), (max(8, int(sheet.p(0.20))), max(2, int(sheet.p(0.003)))), seed + 1, order=1)
    return rgb(hexcol)[None, None, :] * (1.0 + mottle * m + streak * s)[..., None]


def paint_on(ground, a, hexcol, sheet, seed, var=0.02):
    """Letters in paint: the colour a touch uneven (thicker and thinner coats)."""
    v = smooth_noise(a.shape, max(4, int(sheet.p(0.02))), seed)
    col = rgb(hexcol)[None, None, :] * (1.0 + var * v)[..., None]
    return mix(ground, col, np.clip(a, 0, 1))


def shift(a, dx, dy):
    return ndimage.shift(a, (dy, dx), order=1, mode='constant', cval=0.0)


def rounded_rect_mask(sheet, x0, y0, x1, y1, r, width, seed=0):
    """A pinstripe: a rounded rectangle's outline, width metres, drawn as a painter's line (it wanders a little)."""
    m = sheet.mask()
    d = ImageDraw.Draw(m)
    d.rounded_rectangle([sheet.p(x0), sheet.p(y0), sheet.p(x1), sheet.p(y1)], radius=sheet.p(r), outline=255,
                        width=max(1, int(round(sheet.p(width)))))
    return wobble(arr(m), sheet, 0.25, 30, seed)


def gold_paint(ground, a, sheet, seed):
    """A painted gold line or ornament (not leaf): flat gold, slightly uneven."""
    return paint_on(ground, a, GOLD, sheet, seed, var=0.05)


