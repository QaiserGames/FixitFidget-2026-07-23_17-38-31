def read_drinks(folder):
    """Every Drink_*.asset in folder: its drinkName and integer price, as the game's DrinkDefinition holds them."""
    drinks = []
    for path in sorted(glob.glob(os.path.join(folder, 'Drink_*.asset'))):
        text = open(path, encoding='utf-8').read()
        name = re.search(r'^\s*drinkName:\s*(.+?)\s*$', text, re.M)
        price = re.search(r'^\s*price:\s*(-?\d+)\s*$', text, re.M)
        if not name or not price:
            raise ValueError('No drinkName or price in ' + path)
        drinks.append({'name': name.group(1).strip().strip('"\''), 'price': int(price.group(1)),
                       'file': os.path.basename(path)})
    if not drinks:
        raise FileNotFoundError('No Drink_*.asset in ' + folder)
    known = {d['name']: d for d in drinks}
    ordered = [known[n] for n in CAFE_ORDER if n in known]
    ordered += sorted((d for d in drinks if d['name'] not in CAFE_ORDER), key=lambda d: (d['price'], d['name']))
    return ordered


