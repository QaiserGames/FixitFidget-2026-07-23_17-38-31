def mat_stone(n=1024):
    """CF_Stone: a pale honed stone (a limestone-quartzite look), soft cloudy veins, 1 tile = 2.0 m.

    10 Oct (Claude, after the first Unity photos): the first draw (#E6E1D7, veins #C9C3B8 at 0.28-0.38, clouds 2 %) had a
    standard deviation of 2 levels: under the counter's four pendants it read as a white plastic slab. A touch darker and
    warmer, clouds you can see (5 %), taupe veins at about twice the strength: stone from the queue, quiet from above."""
    base, vein = rgb('#DDD6C9'), rgb('#B3AA9C')
    cloud = fft_noise(n, 2.4, 11)
    cloud2 = fft_noise(n, 1.6, 12)
    img = base[None, None, :] * (1.0 + 0.050 * cloud[..., None] + 0.018 * cloud2[..., None])
    # soft veins: two families of warped bands at integer frequencies (so they tile), drifting on a diagonal
    y, x = np.mgrid[0:n, 0:n].astype(np.float32) / n
    warp = fft_noise(n, 2.6, 13) * 0.55 + fft_noise(n, 2.0, 14) * 0.12
    veins = np.zeros((n, n), np.float32)
    for (a, b, w, k, seed) in ((1, 2, 0.060, 0.62, 21), (2, -1, 0.040, 0.52, 22), (3, 1, 0.016, 0.46, 23)):
        ph = 2 * np.pi * (a * x + b * y) + 2 * np.pi * warp * (1.0 + 0.3 * fft_noise(n, 2.2, seed))
        d = np.abs(np.sin(ph))
        line = np.exp(-(d / w) ** 2)
        fade = smoothstep(-0.1, 0.7, fft_noise(n, 1.9, seed + 100))   # veins come and go, never a stripe pattern
        veins = np.maximum(veins, line * fade * k)
    hair = 1.0 - np.abs(fft_noise(n, 1.9, 31))
    veins = np.maximum(veins, smoothstep(0.985, 0.997, hair) * 0.55)
    veins = ndimage.gaussian_filter(veins, 1.2, mode='wrap')
    img = mix(img, vein[None, None, :] * (1 + 0.02 * cloud2[..., None]), np.clip(veins, 0, 1))
    speck = band_noise(n, 180, 512, 15)
    img *= (1.0 + 0.010 * speck)[..., None]
    height = 0.00004 * speck - 0.00003 * veins          # honed: almost flat
    return img, normal_map(height, TILES['CF_Stone'], 1.0)


def mat_tile(n=1024):
    """CF_Tile: cream glazed tile 5 x 20 cm, vertical stack (20 across, 5 up a metre), +-4 % per tile, 2 mm warm grout."""
    N = 2 * n                                           # drawn at 2x, box-filtered down: the grout stays crisp
    tile_m = TILES['CF_Tile']
    px = tile_m / N
    cols, rows = 20, 5
    y, x = np.mgrid[0:N, 0:N].astype(np.float32)
    xm, ym = (x + 0.5) * px, (y + 0.5) * px
    ci = np.floor(xm / (tile_m / cols)).astype(int) % cols
    ri = np.floor(ym / (tile_m / rows)).astype(int) % rows
    lx = xm - ci * (tile_m / cols)                      # position inside the tile, metres
    ly = ym - ri * (tile_m / rows)
    tw, th = tile_m / cols, tile_m / rows
    edge = np.minimum(np.minimum(lx, tw - lx), np.minimum(ly, th - ly))   # distance to the tile's edge
    grout_half = 0.001                                  # 2 mm joints: 1 mm of each tile's side
    r = rng_for(41)
    tone = r.uniform(-0.04, 0.04, (rows, cols)).astype(np.float32)        # +-4 % per tile
    warm = r.uniform(-0.006, 0.006, (rows, cols)).astype(np.float32)
    base = rgb('#EDE4D3')
    t = tone[ri, ci]
    img = base[None, None, :] * (1.0 + t)[..., None]
    img[..., 0] *= (1.0 + warm[ri, ci])
    img[..., 2] *= (1.0 - warm[ri, ci])
    # the glaze: a little cloud inside each tile, thicker (a touch darker) where it pools at the edges
    glaze = fft_noise(N, 2.2, 42)
    img *= (1.0 + 0.012 * glaze)[..., None]
    pool = 1.0 - smoothstep(0.0012, 0.006, edge)
    img *= (1.0 - 0.035 * pool)[..., None]
    grout = (edge < grout_half).astype(np.float32)
    grout_col = rgb('#CFC6B6') * (1.0 + 0.03 * fft_noise(N, 1.2, 43))[..., None]
    img = mix(img, grout_col, grout)
    # height: a cushioned face (rolls off over the last 2.5 mm), glaze waviness, the joint 1.5 mm down
    cushion = -0.0006 * (1.0 - smoothstep(grout_half, grout_half + 0.0025, edge)) ** 2
    wav = 0.00012 * fft_noise(N, 2.0, 44) + 0.00006 * band_noise(N, 20, 60, 45)
    height = np.where(grout > 0.5, -0.0015, cushion + wav)
    img = down2(img)
    height = down2(height)
    return img, normal_map(height, tile_m, 1.0)


def wood_grain(h, w, seed, straight=True, px_m=0.00176, along=0, contrast=1.0):
    """
    Grain for one board, (h along the board, w across), metres per pixel px_m: straight (rift) grain or a cathedral
    (plain-sawn arches). Returns a field in [-1, 1]: + is darker (latewood, streaks).
    """
    r = rng_for(seed)
    yy, xx = np.mgrid[0:h, 0:w].astype(np.float32)
    ym, xm = yy * px_m + along, xx * px_m
    wob = smooth_noise((h, w), (max(4, int(0.30 / px_m)), max(4, int(0.06 / px_m))), seed + 1) * 0.006
    wob += smooth_noise((h, w), (max(4, int(0.08 / px_m)), max(4, int(0.02 / px_m))), seed + 2) * 0.0015
    if straight:
        spacing = r.uniform(0.007, 0.012)                # what reads of rift grain: bands 7-12 mm apart
        u = xm + wob + r.uniform(0, 1)
        width = 0.20
    else:
        spacing = r.uniform(0.010, 0.016)                # plain-sawn: the rings cut at a shallow angle, wider
        cx = r.uniform(0.35, 0.65) * w * px_m
        y0 = r.uniform(0.25, 0.75) * h * px_m
        span = h * px_m * r.uniform(0.35, 0.6)
        amp = r.uniform(0.03, 0.06)
        u = np.abs(xm - cx) + wob - amp * np.sqrt(np.clip(1 - ((ym - y0) / span) ** 2, 0, 1))
        width = 0.24
    phase = (u / spacing) % 1.0
    ring = np.exp(-((phase - 0.5) / width) ** 2) * 2 - 1
    streak = smooth_noise((h, w), (max(3, int(0.35 / px_m)), max(2, int(0.012 / px_m))), seed + 3)
    pores = smooth_noise((h, w), (max(2, int(0.03 / px_m)), 1), seed + 4)
    return np.clip(ring * 0.55 * contrast + streak * 0.35 + pores * 0.15, -1, 1)


def mat_floor_oak(n=1024):
    """CF_Floor_Oak: pale white oak, boards 18 cm, staggered butt joints, low contrast; 1 tile = 1.8 m (10 boards)."""
    tile_m = TILES['CF_Floor_Oak']
    boards = 10
    bw = n // boards                                     # 102 px; the last board takes the remainder
    px = tile_m / n
    r = rng_for(51)
    light, mid, seam = rgb('#D9C7A8'), rgb('#CDB797'), rgb('#B49D7C')
    img = np.zeros((n, n, 3), np.float32)
    height = np.zeros((n, n), np.float32)
    edges_x = [int(round(i * n / boards)) for i in range(boards + 1)]
    prev = []
    for b in range(boards):
        x0, x1 = edges_x[b], edges_x[b + 1]
        w = x1 - x0
        # joints for this column, wrapped on the tile: 1 or 2 per 1.8 m, at least 0.25 m from the last column's
        for _ in range(200):
            k = r.integers(1, 3)
            js = sorted(r.uniform(0, tile_m, k))
            if k == 2 and (js[1] - js[0] < 0.6 or tile_m - js[1] + js[0] < 0.6):
                continue
            if all(min(abs(a - p), tile_m - abs(a - p)) > 0.25 for a in js for p in prev):
                break
        prev = js
        jpx = [int(round(j / px)) % n for j in js]
        # each board between two joints is its own board: its own tone and grain
        cuts = sorted(jpx)
        segs = [(cuts[i], cuts[(i + 1) % len(cuts)]) for i in range(len(cuts))]
        for si, (a, bnd) in enumerate(segs):
            length = (bnd - a) % n or n
            rows = (np.arange(length) + a) % n
            tone = r.uniform(0, 1)
            col = mix(mid[None, :], light[None, :], np.array([[tone]], np.float32))[0]
            col = col * (1.0 + r.uniform(-0.025, 0.025))
            straight = r.uniform() < 0.6
            g = wood_grain(length, w, int(r.integers(1, 1 << 30)), straight=straight, px_m=px, contrast=1.0)
            board = col[None, None, :] * (1.0 - 0.075 * g[..., None])
            # medullary ray flecks on the rift boards (white oak's own mark): short light dashes across the grain
            if straight:
                fl = smooth_noise((length, w), (3, 9), int(r.integers(1, 1 << 30)), order=1)
                board *= (1.0 + 0.03 * smoothstep(0.75, 0.95, fl))[..., None]
            img[rows, x0:x1] = board
            height[rows, x0:x1] = -0.00006 * g
        # the butt joints: a fine dark line, eased edges
        for j in jpx:
            for d, k_ in ((-1, 0.35), (0, 1.0), (1, 0.35)):
                rr = (j + d) % n
                img[rr, x0:x1] = mix(img[rr, x0:x1], seam[None, :], np.full((x1 - x0,), 0.55 * k_, np.float32))
                height[rr, x0:x1] -= 0.0004 * k_
    # the long seams between boards (on the tile's edge too, so the tiling makes a whole seam)
    for xe in edges_x[:-1]:
        for d, k_ in ((-1, 0.35), (0, 1.0), (1, 0.35)):
            cc = (xe + d) % n
            img[:, cc] = mix(img[:, cc], seam[None, :], np.full((n,), 0.5 * k_, np.float32))
            height[:, cc] -= 0.0004 * k_
    img *= (1.0 + 0.012 * fft_noise(n, 2.0, 52))[..., None]
    return img, normal_map(height, tile_m, 1.0)


def mat_floor_concrete(n=1024):
    """CF_Floor_Concrete: warm grey polished concrete, soft mottle, a faint saw-cut joint on the edges; 1 tile = 3 m."""
    tile_m = TILES['CF_Floor_Concrete']
    base, mott = rgb('#A8A196'), rgb('#BDB6AA')
    m1 = fft_noise(n, 2.3, 61)
    m2 = fft_noise(n, 1.7, 62)
    m3 = band_noise(n, 6, 40, 66)                           # patches 7-50 cm: the trowel and the grind
    t = smoothstep(-0.45, 0.65, 0.8 * m1 + 0.25 * m2 + 0.45 * m3)
    img = mix(base[None, None, :], mott[None, None, :], t * 0.62)
    img *= (1.0 + 0.012 * fft_noise(n, 1.3, 63) + 0.010 * band_noise(n, 40, 160, 67))[..., None]
    # the fine aggregate a polished floor shows: sparse specks, some darker, some lighter
    r = rng_for(64)
    sp = r.uniform(0, 1, (n, n)).astype(np.float32)
    dark = (sp < 0.006).astype(np.float32)
    lite = (sp > 0.995).astype(np.float32)
    dark = ndimage.gaussian_filter(dark, 0.6, mode='wrap') * 2.5
    lite = ndimage.gaussian_filter(lite, 0.6, mode='wrap') * 2.5
    img *= (1.0 - 0.10 * np.clip(dark, 0, 1) + 0.06 * np.clip(lite, 0, 1))[..., None]
    height = 0.00003 * fft_noise(n, 1.5, 65)
    # the saw cut: one pixel each side of the tile's edge (3 mm wide, ~1 cm deep), a grey line with eased lips
    joint = np.zeros((n, n), np.float32)
    joint[:, 0] = joint[:, -1] = 1.0
    joint[0, :] = joint[-1, :] = 1.0
    lip = np.zeros((n, n), np.float32)
    lip[:, 1] = lip[:, -2] = 1.0
    lip[1, :] = lip[-2, :] = 1.0
    img = mix(img, rgb('#857E74')[None, None, :], joint * 0.55 + lip * 0.10)
    height = height - 0.004 * joint - 0.0006 * lip
    return img, normal_map(height, tile_m, 0.6)


def mat_boards(n=1024):
    """CF_Boards: vertical V-groove boards 9 cm wide in espresso tones; 1 tile = 0.9 m (10 boards)."""
    N = 2 * n
    tile_m = TILES['CF_Boards']
    px = tile_m / N
    boards = 10
    base, dark, light = rgb('#4A3422'), rgb('#3E2C1E'), rgb('#543A26')
    img = np.zeros((N, N, 3), np.float32)
    height = np.zeros((N, N), np.float32)
    edges = [int(round(i * N / boards)) for i in range(boards + 1)]
    r = rng_for(71)
    yy = np.arange(N, dtype=np.float32)[:, None]
    for b in range(boards):
        x0, x1 = edges[b], edges[b + 1]
        w = x1 - x0
        xx = np.arange(w, dtype=np.float32)[None, :]
        # straight grain that repeats along the board's length every 0.9 m (integer waves), so the tile is seamless
        sp = r.uniform(0.007, 0.012)
        ph0 = r.uniform(0, 1)
        wav = np.zeros((N, w), np.float32)
        for k in (1, 2, 3, 5):
            wav += r.uniform(0.0006, 0.0025) / k * np.sin(2 * np.pi * (k * yy / N + r.uniform(0, 1)) + xx * px * r.uniform(5, 25))
        u = xx * px + wav + ph0 * sp
        ring = np.exp(-(((u / sp) % 1.0 - 0.5) / 0.22) ** 2) * 2 - 1
        pore = band_noise(N, 40, 400, int(r.integers(1, 1 << 30)), aniso=(8.0, 1.0))[:, :w]
        streak = band_noise(N, 4, 60, int(r.integers(1, 1 << 30)), aniso=(10.0, 1.0))[:, :w]
        g = np.clip(0.5 * ring + 0.2 * pore + 0.55 * streak, -1, 1)
        tone = r.uniform(-1, 1)
        col = base * (1.0 + 0.05 * tone)
        board = mix(col[None, None, :] * np.ones((N, w, 1), np.float32), dark[None, None, :], np.clip(g, 0, 1) * 0.85)
        board = mix(board, light[None, None, :] * 1.06, np.clip(-g, 0, 1) * 0.75)
        img[:, x0:x1] = board
        height[:, x0:x1] = -0.00003 * g
    # the V-grooves: 4 mm wide, 2 mm deep, on each board edge (the tile's own edge carries half of one)
    xs = (np.arange(N, dtype=np.float32) + 0.5) * px
    d = np.min(np.abs(xs[None, :] - (np.array(edges, np.float32) * px)[:, None]), axis=0)
    v = np.clip(1.0 - d / 0.002, 0, 1)
    height -= 0.002 * v[None, :]
    shade = (v ** 2)[None, :] * np.ones((N, 1), np.float32)
    img = mix(img, rgb('#24190F')[None, None, :], shade * 0.55)
    img = down2(img)
    height = down2(height)
    return img, normal_map(height, tile_m, 1.0)


def mat_fabric(n=1024):
    """CF_Fabric: an oat upholstery weave (2/2 basket, slubbed heathered yarn); 1 tile = 0.25 m, 256 threads a tile."""
    tile_m = TILES['CF_Fabric']
    th = 256
    p = n // th                                          # 4 px a thread
    base = rgb('#A8957C')
    r = rng_for(81)
    y, x = np.mgrid[0:n, 0:n]
    ti_x, ti_y = x // p, y // p                          # thread index (warp runs up the picture, weft across)
    fx, fy = (x % p + 0.5) / p, (y % p + 0.5) / p        # position across the thread
    # 2/2 basket: blocks of 2 x 2 threads, warp over in one block, weft over in the next
    warp_up = ((ti_x // 2 + ti_y // 2) % 2 == 0)
    warp_tone = r.uniform(-0.025, 0.025, th).astype(np.float32)
    weft_tone = r.uniform(-0.025, 0.025, th).astype(np.float32)
    along = band_noise(n, 8, 120, 87)                    # each yarn lighter and darker along its length (slubs)
    warp_th = 0.80 + 0.18 * band_noise(n, 3, 40, 83)[y % n, (ti_x * 7) % n]
    weft_th = 0.80 + 0.18 * band_noise(n, 3, 40, 84)[(ti_y * 7) % n, x % n]
    prof_w = np.clip(1 - np.abs(fx - 0.5) * 2 / warp_th, 0, 1)        # 1 at the yarn's middle
    prof_e = np.clip(1 - np.abs(fy - 0.5) * 2 / weft_th, 0, 1)
    top_prof = np.where(warp_up, prof_w, prof_e)
    tone = np.where(warp_up, warp_tone[ti_x % th] + 0.05 * along[y % n, (ti_x * 13) % n],
                    weft_tone[ti_y % th] + 0.05 * along[(ti_y * 13) % n, x % n])
    fibre = band_noise(n, 200, 512, 85)
    heather = (r.uniform(0, 1, (n, n)) < 0.06).astype(np.float32)
    heather = ndimage.gaussian_filter(heather, 0.5, mode='wrap')
    lum = 1.0 + tone + 0.05 * fibre + 0.10 * heather - 0.20 * (1 - np.sqrt(top_prof))
    img = base[None, None, :] * lum[..., None]
    img *= (1.0 + 0.025 * fft_noise(n, 2.0, 86))[..., None]
    height = 0.0004 * np.sqrt(top_prof) + 0.0001 * fibre
    return img, normal_map(height, tile_m, 0.35)


