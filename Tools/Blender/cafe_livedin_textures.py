def draw_rug(out_dir):
    """
    LI_RugCorner: a weft-faced flatweave, 1.60 x 1.10 (after IKEA's TIPHEDE, flatwoven cotton, 2 mm, and the 110 x 160
    flatwoven wool rugs sold at that size). Calm on purpose (the redesign took four loud floor pieces out; this one comes
    back quieter): an oat field, and near each end a muted rust band between two charcoal pinstripes. The warp runs the
    length (u), so the weft's picks are fine ribs across it and the stripes are bands of picks; each pick's yarn is a
    shade off the next, and the weft rides over and under the warp in a brick pattern (the weave you see up close). The
    ends are whipped hems (no fringe: the old kilim's fringe was one of the loud things), the long edges twined cords.
    """
    W, D = RUG
    N = 2048                                           # drawn at 2x, box-filtered to 1024
    x = (np.arange(N) + 0.5) / N * W                   # metres along the rug (u, left to right)
    y = (np.arange(N) + 0.5) / N * D                   # metres across (image rows, top = the back edge)
    X, Y = np.meshgrid(x, y)
    oat, oat_dk, rust, char = rgb('#C9B89B'), rgb('#AE9A7B'), rgb('#9A5A3E'), rgb('#4A4541')
    e = np.minimum(X, W - X)                           # distance from the nearer end
    f = np.minimum(Y, D - Y)                           # distance from the nearer long edge
    # the weft's picks: 2.6 mm apart along u; a stripe edge falls on a pick, with a half-pick dovetail every 6 mm across
    pick = 0.0026
    pi_ = np.floor(X / pick).astype(int)
    dove = (np.floor(Y / 0.006).astype(int) % 2) * 0.5 * pick
    ed = np.minimum(X + dove, W - X + dove)
    band = [(0.022, 'hem'), (0.105, 'oat'), (0.118, 'char'), (0.132, 'oat'), (0.240, 'rust'), (0.254, 'oat'),
            (0.267, 'char')]
    img = np.empty((N, N, 3), np.float32)
    img[:] = oat
    lo = 0.0
    for hi, name in band:
        m = (ed >= lo) & (ed < hi)
        img[m] = {'hem': oat_dk, 'oat': oat, 'char': char, 'rust': rust}[name]
        lo = hi
    r = dct.rng_for(1201)
    tone = r.uniform(-0.035, 0.035, pi_.max() + 2).astype(np.float32)          # each pick's yarn a shade off
    img *= (1.0 + tone[pi_])[..., None]
    # the weave: the weft shows between the warps (5 mm apart) in a brick pattern; each float is a small bump
    warp = 0.005
    yy = (Y / warp + 0.5 * (pi_ % 2)) % 1.0
    xx = (X / pick) % 1.0
    bump = np.sin(np.pi * yy) ** 0.7 * np.sin(np.pi * xx) ** 0.5
    img *= (0.93 + 0.10 * bump)[..., None]
    # abrash (dye lots along the length) and a soft cloud, then the fibre
    ab = ndimage.gaussian_filter1d(r.standard_normal(N).astype(np.float32), N / 40.0)
    ab /= (np.abs(ab).max() + 1e-6)
    img *= (1.0 + 0.020 * ab[None, :] + 0.018 * noise2((N, N), 2.2, 1202))[..., None]
    img *= (1.0 + 0.030 * band2((N, N), 250, 900, 1203))[..., None]
    # the whipped hems: diagonal wraps every 4 mm, a little darker
    hem = e < 0.022
    whip = ((X + Y) / 0.004) % 1.0
    img[hem] *= (0.90 + 0.14 * np.sin(np.pi * whip[hem]) ** 2)[..., None]
    # the twined selvedges: 10 mm, charcoal and oat twisted (short diagonal dashes)
    selv = (f < 0.010) & (e >= 0.020)
    tw = (((X - Y * 0.8) / 0.006) % 1.0) < 0.5
    img[selv & tw] = char * 1.05
    img[selv & ~tw] = oat_dk * 0.95
    img = dct.down2(img)
    save_rgb(img, out_path(out_dir, 'LI_RugCorner.png'))
    return img


# ============================================================================================= 2. the entry mat (coir)

def draw_coir(out_dir):
    """
    LI_CoirMat: plain natural coir, 1.20 x 0.70, 17 mm on a PVC back (COBA's coir entrance matting: natural coconut
    fibre, 17 mm, cut to size from the roll). Tufts in rows 5 mm apart, each a brush of stiff fibres whose tips catch the
    light (gold) over darker voids; no pattern, no words (his "plain coir-coloured"). The outer 6 mm, where the cut edge
    is bevelled, is denser and a touch darker.
    """
    W, D = COIR
    Wp, Hp = 2048, 1024                                # 2x of 1024 x 512
    x = (np.arange(Wp) + 0.5) / Wp * W
    y = (np.arange(Hp) + 0.5) / Hp * D
    X, Y = np.meshgrid(x, y)
    r = dct.rng_for(1301)
    pitch_x, pitch_y = 0.0050, 0.0042
    # tufts on a jittered grid: distance to the tuft centre in the pixel's cell (and the next ones over)
    ix, iy = np.floor(X / pitch_x).astype(int), np.floor(Y / pitch_y).astype(int)
    jx = r.uniform(-0.3, 0.3, (iy.max() + 3, ix.max() + 3)).astype(np.float32)
    jy = r.uniform(-0.3, 0.3, (iy.max() + 3, ix.max() + 3)).astype(np.float32)
    tt = r.uniform(-1, 1, (iy.max() + 3, ix.max() + 3)).astype(np.float32)
    best = np.full(X.shape, 9.0, np.float32)
    tone = np.zeros(X.shape, np.float32)
    for dy in (-1, 0, 1):
        for dx in (-1, 0, 1):
            cx_i, cy_i = np.clip(ix + dx, 0, None), np.clip(iy + dy, 0, None)
            cx = (cx_i + 0.5 + jx[cy_i, cx_i]) * pitch_x
            cy = (cy_i + 0.5 + jy[cy_i, cx_i]) * pitch_y
            d = np.hypot((X - cx) / pitch_x, (Y - cy) / pitch_y)
            closer = d < best
            best = np.where(closer, d, best)
            tone = np.where(closer, tt[cy_i, cx_i], tone)
    tuft = np.clip(1.0 - best / 0.75, 0, 1)
    fibre = band2((Hp, Wp), 300, 1000, 1302)
    void, base, tip = rgb('#4E331C'), rgb('#A07545'), rgb('#CDA46C')
    img = mix(void, base, np.clip(0.30 + 0.80 * tuft, 0, 1))
    img *= (1.0 + 0.06 * tone + 0.04 * noise2((Hp, Wp), 2.0, 1303) + 0.05 * fibre)[..., None]
    # the bristles: stiff fibres lying every which way over the tufts, light tips over darker shafts (coir's look:
    # coarse, straight, never a weave). Short strokes, 3-9 mm, drawn light and dark.
    ppm = Wp / W
    for colour, count, seed, alpha in (('#3E2914', 26000, 1304, 0.55), ('#B78B55', 30000, 1305, 0.6),
                                       ('#D9B47C', 16000, 1306, 0.75)):
        layer = Image.new('L', (Wp, Hp), 0)
        dl = ImageDraw.Draw(layer)
        rr = dct.rng_for(seed)
        cxs, cys = rr.uniform(0, Wp, count), rr.uniform(0, Hp, count)
        ang = rr.uniform(0, math.pi, count)
        ln = rr.uniform(0.003, 0.009, count) * ppm
        for cx, cy, a, l in zip(cxs, cys, ang, ln):
            dx, dy = math.cos(a) * l / 2, math.sin(a) * l / 2
            dl.line([(cx - dx, cy - dy), (cx + dx, cy + dy)], fill=255, width=1)
        img = mix(img, rgb(colour), arr(layer) * alpha)
    # the cut edge (the bevel, seen from above): denser, a touch darker
    e = np.minimum(np.minimum(X, W - X), np.minimum(Y, D - Y))
    edge = 1.0 - smoothstep(0.003, 0.008, e)
    img = mix(img, rgb('#7A5532') * (1.0 + 0.05 * fibre)[..., None], edge * 0.7)
    img = dct.down2(img)
    save_rgb(img, out_path(out_dir, 'LI_CoirMat.png'))
    return img


# ============================================================================================= 3. the till mat (rubber)

def draw_rubber(out_dir):
    """
    LI_RubberMat: a black anti-fatigue mat, 36 x 24 x 1/2 in, bevelled all round (the restaurant mats sold at that size,
    e.g. Serve Secure's, and Winco's RBM-35K: 1/2 in, bevelled so it lies flat). Drawn to match the bench's and the drink
    station's mats (a dark slab with a grid of drainage holes): the ramp (25 mm, seen from above) plain and a little
    worn, then a grid of rounded-square drainage holes, 19 mm on a 36 mm pitch, dark inside, the far wall of each hole
    catching the light so it reads as a hole and not a painted square.
    """
    W, D = RUBBER
    sh = Sheet(W, D, (1024, 1024), ss=2.0)
    Hh, Ww = sh.H, sh.W
    r = dct.rng_for(1401)
    base = rgb('#2B2927')
    img = base[None, None, :] * (1.0 + 0.035 * dct.smooth_noise((Hh, Ww), int(sh.p(0.08)), 1402)
                                 + 0.020 * dct.smooth_noise((Hh, Ww), int(sh.p(0.006)), 1403))[..., None]
    yy, xx = np.mgrid[0:Hh, 0:Ww].astype(np.float32)
    X, Y = xx / sh.ppm, yy / sh.ppm
    e = np.minimum(np.minimum(X, W - X), np.minimum(Y, D - Y))
    ramp = e < RUBBER_RAMP
    img[ramp] *= 1.10                                  # the ramp: worn a little lighter by shoes
    crest = np.exp(-((e - RUBBER_RAMP) / 0.0012) ** 2)  # the line where the ramp meets the top
    img *= (1.0 + 0.25 * crest)[..., None]
    # the holes
    pitch, hole, rad = 0.036, 0.019, 0.0045
    nx = int((W - 2 * (RUBBER_RAMP + 0.012)) // pitch)
    ny = int((D - 2 * (RUBBER_RAMP + 0.012)) // pitch)
    x0 = (W - (nx - 1) * pitch) / 2
    y0 = (D - (ny - 1) * pitch) / 2
    holes = Image.new('L', (Ww, Hh), 0)
    rim = Image.new('L', (Ww, Hh), 0)
    dh, dr = ImageDraw.Draw(holes), ImageDraw.Draw(rim)
    for j in range(ny):
        for i in range(nx):
            cx, cy = x0 + i * pitch, y0 + j * pitch
            box = [sh.p(cx - hole / 2), sh.p(cy - hole / 2), sh.p(cx + hole / 2), sh.p(cy + hole / 2)]
            dh.rounded_rectangle(box, radius=sh.p(rad), fill=255)
            # the far wall (toward the top of the picture, the light's side): a crescent inside the top edge
            dr.rounded_rectangle([box[0], box[1], box[2], box[1] + sh.p(hole * 0.32)], radius=sh.p(rad), fill=255)
    h = ndimage.gaussian_filter(arr(holes), 0.8)
    wall = ndimage.gaussian_filter(arr(rim), 1.2) * h
    img = mix(img, rgb('#0B0A09'), h * 0.92)
    img = mix(img, rgb('#3E3a36'), wall * 0.55)
    # a soft highlight on each hole's lip (the moulded edge), the near side
    lip = np.clip(ndimage.gaussian_filter(arr(holes), 2.5) - h, 0, 1)
    img *= (1.0 + 0.30 * lip)[..., None]
    sh.save(img, out_path(out_dir, 'LI_RubberMat.png'))
    return nx * ny


