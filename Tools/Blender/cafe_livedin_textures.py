def _icon(d, kind, cx, cy, s, P, fill=255, bg=0):
    """A bold white pictogram in a box of side s (metres) centred at (cx, cy), drawn on an 'L' mask with P = sheet.p."""
    def R(x0, y0, x1, y1, **kw):
        d.rectangle([P(cx + x0 * s), P(cy + y0 * s), P(cx + x1 * s), P(cy + y1 * s)], **kw)

    def RR(x0, y0, x1, y1, r, **kw):
        d.rounded_rectangle([P(cx + x0 * s), P(cy + y0 * s), P(cx + x1 * s), P(cy + y1 * s)], radius=P(r * s), **kw)

    def E(x0, y0, x1, y1, **kw):
        d.ellipse([P(cx + x0 * s), P(cy + y0 * s), P(cx + x1 * s), P(cy + y1 * s)], **kw)

    def Poly(pts, **kw):
        d.polygon([(P(cx + a * s), P(cy + b * s)) for a, b in pts], **kw)

    lw = max(1, int(P(0.045 * s)))
    if kind == 'bottle':
        RR(-0.17, -0.12, 0.17, 0.50, 0.10, fill=fill)                      # body
        Poly([(-0.17, -0.10), (-0.07, -0.30), (0.07, -0.30), (0.17, -0.10)], fill=fill)   # shoulder
        R(-0.07, -0.42, 0.07, -0.28, fill=fill)                             # neck
        R(-0.09, -0.50, 0.09, -0.42, fill=fill)                             # cap
        R(-0.17, 0.08, 0.17, 0.26, fill=bg)                                 # the label band
        R(-0.13, 0.12, 0.13, 0.22, fill=fill)
    elif kind == 'can':
        RR(-0.24, -0.42, 0.24, 0.46, 0.06, fill=fill)
        R(-0.24, -0.36, 0.24, -0.32, fill=bg)                               # the top rim line
        R(-0.24, 0.38, 0.24, 0.42, fill=bg)
        E(-0.08, -0.49, 0.08, -0.40, outline=fill, width=lw)                # the ring pull
    elif kind == 'box':
        Poly([(-0.42, -0.12), (0.10, -0.12), (0.10, 0.45), (-0.42, 0.45)], fill=fill)          # front
        Poly([(-0.42, -0.16), (0.10, -0.16), (0.40, -0.38), (-0.12, -0.38)], fill=fill)         # top
        Poly([(0.14, -0.14), (0.42, -0.36), (0.42, 0.22), (0.14, 0.44)], fill=fill)            # side
        R(-0.30, 0.02, -0.02, 0.06, fill=bg)                                # a strip of tape
    elif kind == 'cup':
        Poly([(-0.30, -0.24), (0.30, -0.24), (0.22, 0.48), (-0.22, 0.48)], fill=fill)          # cup
        RR(-0.36, -0.36, 0.36, -0.22, 0.04, fill=fill)                      # lid
        RR(-0.22, -0.46, 0.22, -0.34, 0.04, fill=fill)                      # the lid's dome
        Poly([(-0.27, 0.00), (0.27, 0.00), (0.25, 0.20), (-0.25, 0.20)], fill=bg)              # the sleeve's edges
        Poly([(-0.25, 0.03), (0.25, 0.03), (0.24, 0.17), (-0.24, 0.17)], fill=fill)
    elif kind == 'apple':
        E(-0.32, -0.40, 0.32, -0.02, fill=fill)                             # the top of the core
        E(-0.30, 0.10, 0.30, 0.46, fill=fill)                               # the bottom
        R(-0.12, -0.12, 0.12, 0.20, fill=fill)                              # the bitten waist
        R(-0.025, -0.52, 0.025, -0.36, fill=fill)                           # stem
        Poly([(0.02, -0.46), (0.26, -0.56), (0.20, -0.42)], fill=fill)     # leaf
        E(-0.06, 0.02, -0.01, 0.10, fill=bg)                                # pips
        E(0.01, 0.02, 0.06, 0.10, fill=bg)
    elif kind == 'napkin':
        Poly([(-0.40, -0.40), (0.40, -0.40), (0.40, 0.40), (-0.40, 0.40)], fill=fill)
        Poly([(0.40, 0.04), (0.04, 0.40), (0.40, 0.40)], fill=bg)           # the folded corner
        Poly([(0.33, 0.06), (0.06, 0.33), (0.30, 0.30)], fill=fill)
        R(-0.40, -0.02, 0.0, 0.02, fill=bg)                                 # a fold line
    elif kind == 'wrapper':
        RR(-0.24, -0.16, 0.24, 0.16, 0.05, fill=fill)                       # the sweet
        Poly([(-0.24, 0.0), (-0.48, -0.24), (-0.48, 0.24)], fill=fill)     # twisted ends
        Poly([(0.24, 0.0), (0.48, -0.24), (0.48, 0.24)], fill=fill)
        R(-0.30, -0.03, -0.24, 0.03, fill=bg)
        R(0.24, -0.03, 0.30, 0.03, fill=bg)
    elif kind == 'chips':
        pts = [(-0.32, -0.36)]
        for k in range(1, 9):                                               # crimped top
            pts.append((-0.32 + 0.08 * k, -0.42 if k % 2 else -0.36))
        pts += [(0.32, 0.42)]
        for k in range(1, 9):                                               # crimped bottom
            pts.append((0.32 - 0.08 * k, 0.48 if k % 2 else 0.42))
        Poly(pts, fill=fill)
