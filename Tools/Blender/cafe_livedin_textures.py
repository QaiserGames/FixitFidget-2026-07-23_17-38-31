def noise2(shape, beta, seed):
    """Seamless 1/f^beta noise on a non-square shape (cut from a square tile), range ~[-1, 1]."""
    n = max(shape)
    n = 1 << (n - 1).bit_length()
    return dct.fft_noise(n, beta, seed)[:shape[0], :shape[1]]


def band2(shape, f0, f1, seed):
    n = max(shape)
    n = 1 << (n - 1).bit_length()
    return dct.band_noise(n, f0, f1, seed)[:shape[0], :shape[1]]


def save_rgb(a, path, size=None):
    im = Image.fromarray(np.clip(a + 0.5, 0, 255).astype(np.uint8))
    if size and im.size != tuple(size):
        im = im.resize(size, Image.LANCZOS)
    im.save(path, optimize=True)
    return im


