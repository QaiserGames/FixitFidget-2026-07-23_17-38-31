def mix(a, b, t):
    """a to b by t, where a and b are colours (3,) or pictures (h, w, 3) and t a scalar or a (h, w) weight."""
    t = np.asarray(t, np.float32)
    if t.ndim == 2:
        t = t[..., None]
    return np.asarray(a, np.float32) * (1 - t) + np.asarray(b, np.float32) * t

