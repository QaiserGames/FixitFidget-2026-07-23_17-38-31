def _P(sh, x, y):
    return (sh.p(x), sh.p(y))


def crayon(sh, layer, lines, width, seed, jitter=0.0006):
    """Crayon strokes into an 'L' layer: each polyline wobbles a little, its width breathes along it."""
    d = ImageDraw.Draw(layer)
    r = dct.rng_for(seed)
    for pts in lines:
        if len(pts) < 2:
            continue
        pp = [(x + r.uniform(-jitter, jitter), y + r.uniform(-jitter, jitter)) for x, y in pts]
        # resample long segments so the wobble and the width can vary along them
        fine = []
        for (xa, ya), (xb, yb) in zip(pp, pp[1:]):
            n = max(1, int(math.hypot(xb - xa, yb - ya) / 0.004))
            for i in range(n):
                t = i / n
                fine.append((xa + (xb - xa) * t + r.uniform(-jitter, jitter) * 0.4,
                             ya + (yb - ya) * t + r.uniform(-jitter, jitter) * 0.4))
        fine.append(pp[-1])
        for (xa, ya), (xb, yb) in zip(fine, fine[1:]):
            w = width * r.uniform(0.80, 1.15)
            d.line([_P(sh, xa, ya), _P(sh, xb, yb)], fill=255, width=max(1, int(sh.p(w))))
            rr = sh.p(w) / 2
            d.ellipse([sh.p(xb) - rr, sh.p(yb) - rr, sh.p(xb) + rr, sh.p(yb) + rr], fill=255)


def scribble(sh, layer, poly, angle, spacing, width, seed, overshoot=0.0015):
    """A child's colouring-in: back-and-forth strokes at an angle across the shape, a little over its lines."""
    r = dct.rng_for(seed)
    xs = [p[0] for p in poly]
    ys = [p[1] for p in poly]
    cx, cy = (min(xs) + max(xs)) / 2, (min(ys) + max(ys)) / 2
    R = math.hypot(max(xs) - min(xs), max(ys) - min(ys)) / 2 + 0.01
    a = math.radians(angle)
    ux, uy = math.cos(a), math.sin(a)
    vx, vy = -uy, ux
    tmp = Image.new('L', layer.size, 0)
    zig = []
    k = 0
    t = -R
    while t <= R:
        s0, s1 = -R, R
        p0 = (cx + ux * s0 + vx * t, cy + uy * s0 + vy * t)
        p1 = (cx + ux * s1 + vx * (t + spacing * 0.5), cy + uy * s1 + vy * (t + spacing * 0.5))
        zig += [p0, p1] if k % 2 == 0 else [p1, p0]
        t += spacing * r.uniform(0.85, 1.2)
        k += 1
    crayon(sh, tmp, [zig], width, seed + 1, jitter=0.0008)
    # the shape, grown a little and unevenly (colouring goes over the lines)
    clipm = Image.new('L', layer.size, 0)
    ImageDraw.Draw(clipm).polygon([_P(sh, x, y) for x, y in poly], fill=255)
    grow = ndimage.grey_dilation(arr(clipm), size=(max(1, int(sh.p(overshoot))),) * 2)
    wob = dct.wobble(grow, sh, amp_mm=1.2, wave_mm=10, seed=seed + 2)
    out = np.maximum(arr(layer), arr(tmp) * (wob > 0.5))
    layer.paste(Image.fromarray((out * 255).astype(np.uint8)))


def kid_text(sh, layer, text, x, y_base, cap, seed, width=0.0019, slope=0.0):
    """Hand-printed capitals from GLYPHS: each letter a little bigger or smaller, turned, off the line."""
    r = dct.rng_for(seed)
    lines = []
    cx = x
    for i, ch in enumerate(text):
        if ch == ' ':
            cx += cap * 0.55
            continue
        g = GLYPHS[ch]
        s = cap * r.uniform(0.88, 1.14)
        w = s * (0.32 if ch in '!I' else 0.74)
        rot = math.radians(r.uniform(-7, 7))
        by = y_base + slope * (cx - x) + r.uniform(-0.06, 0.06) * cap
        for poly in g:
            pts = []
            for gx, gy in poly:
                lx, ly = (gx - 0.5) * w, -gy * s
                rx = lx * math.cos(rot) - ly * math.sin(rot)
                ry = lx * math.sin(rot) + ly * math.cos(rot)
                pts.append((cx + w / 2 + rx, by + ry))
            lines.append(pts)
        cx += w + cap * r.uniform(0.18, 0.32)
    crayon(sh, layer, lines, width, seed + 7)
    return cx


